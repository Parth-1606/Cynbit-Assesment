/**
 * Project brief generator.
 * Turns questionnaire answers + the recommendation into a structured,
 * copy/download-ready plain-text document.
 */
import type { Answers, RecommendationResult } from '../types';

export interface BriefSections {
  /** Full formatted document. */
  text: string;
  /** Short one-line summary used as the download filename stem. */
  slug: string;
}

function pad(label: string): string {
  return label.padEnd(22, ' ');
}

function formatDescription(description: string, width = 78): string {
  const words = description.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = '';

  for (const word of words) {
    if ((current + ' ' + word).trim().length > width) {
      lines.push(current.trim());
      current = word;
    } else {
      current = `${current} ${word}`;
    }
  }
  if (current.trim()) lines.push(current.trim());
  return lines.join('\n');
}

/** Builds the full project brief document. */
export function buildProjectBrief(
  answers: Answers,
  recommendation: RecommendationResult,
): BriefSections {
  const { contact } = answers;
  const today = new Date().toISOString().slice(0, 10);
  const rule = '='.repeat(78);

  const lines: string[] = [
    rule,
    'CYNBIT PROJECT BRIEF',
    rule,
    '',
    `Generated on : ${today}`,
    `Prepared for : ${contact.name}${contact.company ? ` (${contact.company})` : ''}`,
    '',
    '-'.repeat(78),
    '1. CUSTOMER INFORMATION',
    '-'.repeat(78),
    `${pad('Full name')}: ${contact.name}`,
    `${pad('Email')}: ${contact.email}`,
    `${pad('Company')}: ${contact.company || 'Not provided'}`,
    '',
    '-'.repeat(78),
    '2. BUSINESS OBJECTIVE',
    '-'.repeat(78),
    formatDescription(answers.goal ?? 'Not specified'),
    '',
    '-'.repeat(78),
    '3. REQUIRED SERVICES',
    '-'.repeat(78),
    `Primary     : ${recommendation.primary.name}`,
    `Also review : ${
      recommendation.additional.length > 0
        ? recommendation.additional.map((service) => service.name).join(', ')
        : 'None - the primary service covers the requirement'
    }`,
    `Selected    : ${answers.solution}`,
    '',
    '-'.repeat(78),
    '4. BUDGET AND TIMELINE',
    '-'.repeat(78),
    `${pad('Budget')}: ${answers.budget}`,
    `${pad('Timeline')}: ${answers.timeline}`,
    `${pad('Match score')}: ${recommendation.matchScore}% (rule-based)`,
    '',
    '-'.repeat(78),
    '5. PROJECT DESCRIPTION',
    '-'.repeat(78),
    formatDescription(contact.description),
    '',
    '-'.repeat(78),
    '6. RECOMMENDED SOLUTION',
    '-'.repeat(78),
    `${recommendation.primary.name} - ${recommendation.primary.tagline}`,
    formatDescription(recommendation.primary.description),
    '',
    'Why this service:',
    ...recommendation.reasons.map((reason, index) => `  ${index + 1}. ${reason}`),
    '',
    'Suggested next steps:',
    ...recommendation.nextSteps.map((step, index) => `  ${index + 1}. ${step}`),
    '',
    rule,
    'Generated by the Cynbit Project Discovery Assistant (transparent rule-based logic).',
    rule,
  ];

  const slug = `${contact.name}-${recommendation.primary.name}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);

  return { text: lines.join('\n'), slug: slug || 'cynbit-project-brief' };
}

/**
 * Copies text to the clipboard.
 *
 * Order of attempts:
 *   1. Async Clipboard API (modern browsers)
 *   2. Hidden-textarea + execCommand (older browsers, denied permissions,
 *      embedded webviews)
 *
 * The fallback runs whenever attempt 1 is unavailable *or* rejects, so a
 * permission failure degrades gracefully instead of surfacing an error.
 */
export async function copyToClipboard(text: string): Promise<void> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return;
    } catch {
      // Permission denied or API blocked - fall through to the legacy path.
    }
  }

  const textarea = document.createElement('textarea');
  textarea.value = text;
  textarea.setAttribute('readonly', '');
  textarea.style.position = 'fixed';
  textarea.style.top = '0';
  textarea.style.left = '0';
  textarea.style.opacity = '0';
  document.body.appendChild(textarea);

  textarea.focus();
  textarea.select();
  textarea.setSelectionRange(0, text.length);

  let copied = false;
  try {
    copied = document.execCommand('copy');
  } catch {
    copied = false;
  }
  document.body.removeChild(textarea);

  if (!copied) throw new Error('Clipboard copy is not supported in this browser.');
}

/** Triggers a .txt download of the brief using a temporary object URL. */
export function downloadBrief(text: string, slug: string): void {
  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);

  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = `${slug}-${new Date().toISOString().slice(0, 10)}.txt`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);

  // Release the URL on the next tick so the download can start.
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}
